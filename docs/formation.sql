create or replace function public.send_training_reminders()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  slot_record record;
  registration_record record;
begin
  for slot_record in
    select id, trainer_id
    from public.training_slot
    where status = 'pending'
      and start between (now() + interval '23 hours 55 minutes') and (now() + interval '24 hours 5 minutes')
  loop
    perform public.send_training_email('trainer_reminder', slot_record.id, slot_record.trainer_id);

    for registration_record in
      select member_id
      from public.registration
      where slot_id = slot_record.id
        and status = 'registered'
    loop
      perform public.send_training_email('member_reminder', slot_record.id, registration_record.member_id);
    end loop;
  end loop;

  for slot_record in
    select id, trainer_id
    from public.training_slot
    where status = 'pending'
      and start between (now() + interval '55 minutes') and (now() + interval '65 minutes')
  loop
    perform public.send_training_email('trainer_reminder', slot_record.id, slot_record.trainer_id);

    for registration_record in
      select member_id
      from public.registration
      where slot_id = slot_record.id
        and status = 'registered'
    loop
      perform public.send_training_email('member_reminder', slot_record.id, registration_record.member_id);
    end loop;
  end loop;
end;
$$;

