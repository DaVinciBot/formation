create or replace function public.send_training_email(
  p_template text,
  p_slot_id bigint,
  p_member_id uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = public, vault, net
as $$
declare
  hook_secret text;
  function_url text;
  auth_token text;
  insert_count integer;
  payload jsonb;
  request_id_value bigint;
  normalized_member_id uuid := coalesce(
    p_member_id,
    '00000000-0000-0000-0000-000000000000'::uuid
  );
begin
  select decrypted_secret
  into hook_secret
  from vault.decrypted_secrets
  where name = 'training_email_hook_secret'
  limit 1;

  select decrypted_secret
  into function_url
  from vault.decrypted_secrets
  where name = 'training_email_function_url'
  limit 1;

  select decrypted_secret
  into auth_token
  from vault.decrypted_secrets
  where name = 'service_key'
  limit 1;

  if hook_secret is null or function_url is null or auth_token is null then
    raise exception 'Email function secrets are missing';
  end if;

  insert into public.training_email_log (template, slot_id, member_id)
  values (p_template, p_slot_id, normalized_member_id)
  on conflict do nothing;

  get diagnostics insert_count = row_count;
  if insert_count = 0 then
    return 0;
  end if;

  payload := jsonb_build_object(
    'template', p_template,
    'slot_id', p_slot_id
  );

  if p_member_id is not null then
    payload := payload || jsonb_build_object('member_id', p_member_id);
  end if;

  request_id_value := net.http_post(
    url := function_url,
    body := payload,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'Authorization', 'Bearer ' || auth_token,
      'apikey', auth_token,
      'x-hook-secret', hook_secret
    ),
    timeout_milliseconds := 5000
  );
  update public.training_email_log
  set request_id = request_id_value
  where template = p_template
    and slot_id = p_slot_id
    and member_id = normalized_member_id;
  return request_id_value;
end;
$$;

